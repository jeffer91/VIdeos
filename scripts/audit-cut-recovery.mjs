import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = (name) => readFileSync(new URL(`../${name}`, import.meta.url), 'utf8');
const bridge = read('src/CutSaveStatusBridge.jsx');
const editor = read('src/CutStudioEnhancer.jsx');
const css = read('src/cut-studio.css');
const app = read('src/ProductionApp.jsx');
const db = read('src/storage.js');
const backup = read('src/ProjectBackupManager.jsx');

assert.match(bridge, /compact\.textContent !== label/, 'The cut save bridge must be idempotent.');
assert.match(bridge, /compact\.disabled !== legacy\.disabled/, 'Disabled synchronization must be idempotent.');
assert.match(bridge, /compact\.getAttribute\('aria-busy'\) !== ariaBusy/, 'ARIA writes must be idempotent.');
assert.doesNotMatch(editor, /media\.controls\s*=\s*false/, 'Keep native playback controls.');
assert.match(editor, /nextMedia\?\.getAttribute\('src'\) \|\| nextMedia\?\.currentSrc/, 'Prefer the current video source.');
assert.match(editor, /media\?\.dataset\?\.blobSize/, 'Skip expensive waveform decoding.');
assert.match(editor, /lengthSeconds > 360/, 'Skip very long recordings.');
assert.match(css, /:has\(> \.cut-studio-enhancer\)/, 'Never hide controls without enhanced editor.');
assert.match(css, /:not\(:has\(> \.cut-studio-enhancer\)\)/, 'Fallback editor must be visible.');
assert.match(app, /getPendingRetake\(projectId, slideNumber\)/, 'Load drafts on reopen.');
assert.match(app, /savePendingRetake\(projectId, slideNumber, take\)/, 'Persist unaccepted retakes.');
assert.match(app, /const previous = await getSlideTake\(meta.projectId, meta.slideNumber\)/, 'Inspect original before recovery.');
assert.match(app, /if \(replacing\) await savePendingRetake\(meta.projectId, meta.slideNumber, take\)/, 'Recovery should stage retakes.');
assert.match(app, /commitAcceptedRetake\(project.id, currentSlide.number, nextTake\)/, 'Atomic replacement required.');
assert.match(db, /transaction\(\[PROJECTS_STORE, TAKES_STORE, META_STORE\], 'readwrite'\)/, 'Retake commits must be atomic.');
assert.match(db, /projectStore\.put\(updatedProject\)/, 'Montage must be invalidated.');
assert.match(db, /export async function getProjectPendingRetakes/, 'Drafts must survive restart.');
assert.match(backup, /pendingRetakes: pendingManifest/, 'Drafts must be included in backups.');
assert.match(backup, /for \(const draft of header.pendingRetakes \|\| \[\]\)/, 'Drafts must be restorable.');
assert.match(app, /window\.dispatchEvent\(new CustomEvent\('videosstudio:project-plan-changed'\)\)/, 'Counters must refresh.');
console.log('Auditoría de Corte, regrabación, recuperación y respaldos: OK');
